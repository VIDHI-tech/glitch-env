import {test,expect} from '@playwright/test';
import {execFileSync} from 'node:child_process';
import {mkdirSync} from 'node:fs';
import {resolve} from 'node:path';

const screenshots=resolve('docs/qa');
const password='GlitchQaOnly2026!';
test('complete M4 admin workflow through the real interface',async({page},testInfo)=>{
 mkdirSync(screenshots,{recursive:true});
 const failures:string[]=[];page.on('pageerror',e=>failures.push(e.message));page.on('console',m=>{if(m.type()==='error'&&!m.text().includes('404 (Not Found)'))failures.push(m.text())});page.on('requestfailed',r=>{if(r.failure()?.errorText!=='net::ERR_ABORTED')failures.push(`${r.failure()?.errorText} ${r.url()}`)});page.on('response',r=>{if(r.status()>=500)failures.push(`${r.status()} ${r.url()}`)});
 await page.goto('/');
 await expect(page.getByRole('heading',{name:'Sign in to GLITCH'})).toBeVisible();
 await page.getByRole('textbox',{name:'Email'}).fill('admin@glitch.local');
 await page.getByLabel('Password').fill(password);
 await page.getByRole('button',{name:'Sign in ↗'}).click();
 await expect(page.getByRole('heading',{name:'Learning starts here.'})).toBeVisible();
 await page.screenshot({path:resolve(screenshots,'m4-dashboard.png'),fullPage:true});
 await page.reload();await expect(page.getByRole('heading',{name:'Learning starts here.'})).toBeVisible();
 await page.getByRole('button',{name:'Open course library ↗'}).click();
 const courseTitle=`GLITCH QA Browser Journey ${Date.now()}`;
 await page.getByRole('textbox',{name:'Title'}).fill(courseTitle);
 await page.getByRole('textbox',{name:'Description'}).fill('TEST-ONLY browser fixture. Not finalized curriculum.');
 await page.getByRole('button',{name:'Create course ↗'}).click();
 await expect(page.getByRole('heading',{name:courseTitle,exact:true})).toBeVisible();
 const courseId=await page.evaluate(async(title)=>{const r=await fetch('/api/v1/admin/builder/courses');const all=await r.json();return all.find((x:{title:string})=>x.title===title).id as string},courseTitle);
 await page.getByRole('textbox',{name:'New week title'}).fill('Week 1 · Discovery & sense-making');
 await page.getByRole('button',{name:'Add week'}).click();
 await page.getByRole('button',{name:'Collapse Week 1 · Discovery & sense-making'}).click();
 await expect(page.getByRole('textbox',{name:'New day title'})).toBeHidden();
 await page.getByRole('button',{name:'Expand Week 1 · Discovery & sense-making'}).click();
 await page.getByRole('textbox',{name:'New day title'}).fill('See First. Explain Later.');
 await page.getByRole('button',{name:'Add day'}).click();
 await page.getByRole('textbox',{name:'New chapter title'}).fill('Observation versus interpretation');
 await page.getByRole('button',{name:'Add chapter'}).click();
 await page.getByRole('textbox',{name:'New unit title'}).fill('QA practice · Observation versus interpretation');
 await page.getByRole('button',{name:'Add unit'}).click();
 await expect(page.getByRole('heading',{name:'Exercise unit'})).toBeVisible();
 await page.getByRole('textbox',{name:'Learning objective'}).fill('Separate observation from interpretation');
 await page.getByRole('textbox',{name:'Content / instructions'}).fill('QA FIXTURE — record an observation and an interpretation.');
 await page.getByRole('textbox',{name:'Exercise prompt'}).fill('QA FIXTURE — explain which statement is observation.');
 await page.getByLabel('Completion policy').selectOption('submit_to_complete');
 await page.getByRole('button',{name:'Save draft'}).click();
 await expect(page.getByText('Unit draft saved.')).toBeVisible();
 await page.screenshot({path:resolve(screenshots,'m4-unit-editor.png'),fullPage:true});
 await page.getByRole('button',{name:'Mark ready'}).click();
 await expect(page.getByText('Version marked ready.')).toBeVisible();
 await page.getByRole('textbox',{name:'New unit title'}).fill('QA draft video');
 await page.getByRole('combobox',{name:'Unit kind'}).selectOption('video');
 await page.getByRole('button',{name:'Add unit'}).click();
 await page.getByRole('button',{name:'Move unit down'}).first().click();
 await expect(page.getByText('Order saved.')).toBeVisible();
 await page.screenshot({path:resolve(screenshots,'m4-course-builder.png'),fullPage:true});
 const mp4=testInfo.outputPath('qa.mp4');
 execFileSync('ffmpeg',['-hide_banner','-loglevel','error','-y','-f','lavfi','-i','color=c=purple:s=640x360:d=2','-pix_fmt','yuv420p','-c:v','libx264',mp4]);
 await page.locator('input[type=file][accept="video/mp4"]').setInputFiles(mp4);
 await page.getByRole('button',{name:'Upload video'}).click();
 await expect(page.getByText('Upload complete. Wait for media processing.')).toBeVisible({timeout:30000});
 const mediaRow=page.locator('.media-row').filter({hasText:'Video'}).last();
 await expect(mediaRow).toContainText('ready',{timeout:60000});
 await page.getByRole('button',{name:'Mark ready'}).click();
 await page.getByRole('combobox',{name:'Prerequisite for QA practice · Observation versus interpretation'}).selectOption({label:'QA draft video'});
 await page.getByRole('button',{name:'Run publication checklist'}).click();
 await expect(page.getByText('Ready to publish')).toBeVisible();
 await page.screenshot({path:resolve(screenshots,'m4-preview.png'),fullPage:true});
 await page.getByRole('button',{name:'Publish immutable release ↗'}).click();
 await expect(page.getByText('Immutable release published.')).toBeVisible();
 const publishedVersion=await page.evaluate(async(id)=>{const r=await fetch(`/api/v1/admin/builder/courses/${id}`);const detail=await r.json();return detail.versions.find((v:{title:string})=>v.title==='QA draft video').id as string},courseId);
 const immutable=await page.request.patch(`/api/v1/admin/builder/unit-versions/${publishedVersion}`,{headers:{origin:'http://127.0.0.1:5173'},data:{title:'Tampered',description:'',learningObjective:'',content:'',required:true}});
 expect(immutable.status()).toBe(409);
 await page.getByRole('button',{name:/QA draft video/}).click();
 await expect(page.getByText('Published version is locked.')).toBeVisible();
 await page.getByRole('button',{name:'Students',exact:false}).click();
 await page.getByRole('combobox',{name:'Select verified student'}).selectOption({label:'QA Student B · student.b@glitch.local'});
 await page.getByRole('button',{name:'Enroll student'}).click();
 await expect(page.getByText('Student enrolled in the latest release.')).toBeVisible();
 await page.getByRole('button',{name:'Progress'}).click();
 await expect(page.getByText('INDIVIDUAL PROGRESS')).toBeVisible();
 await page.screenshot({path:resolve(screenshots,'m4-students.png'),fullPage:true});
 await page.getByRole('button',{name:'Sign out'}).click();
 await expect(page.getByRole('heading',{name:'Sign in to GLITCH'})).toBeVisible();
 await page.getByRole('textbox',{name:'Email'}).fill('content@glitch.local');
 await page.getByLabel('Password').fill(password);
 await page.getByRole('button',{name:'Sign in ↗'}).click();
 await expect(page.getByRole('heading',{name:'Learning starts here.'})).toBeVisible();
 const denied=await page.request.get(`/api/v1/admin/builder/courses/${courseId}`);
 expect(denied.status()).toBe(404);
 expect(failures).toEqual([]);
});
